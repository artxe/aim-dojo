/**
 * @param {string} message
 * @param {number} duration
 * @returns {void}
 */
export function send_toast(message, duration) {
	const p = document.createElement("p")
	p.textContent = message
	toast_el.prepend(p)
	p.setAttribute(
		"timer",
		String(
			setTimeout(() => p.remove(), duration)
		)
	)
}
/**
 * @param {Element} el
 * @param {string} name
 * @param {string|number} value
 * @returns {void}
 */
export function set_attr_if_changed(el, name, value) {
	const s = String(value)
	if (el.getAttribute(name) != s) {
		el.setAttribute(name, s)
	}
}
/**
 * @param {HTMLSpanElement} score_el
 * @param {HTMLButtonElement} clear_btn
 * @param {number} score
 * @returns {void}
 */
export function set_best_score(score_el, clear_btn, score) {
	set_text_if_changed(score_el, score)
	clear_btn.disabled = !score
}
/**
 * @param {HTMLSpanElement} el
 * @param {string|number} text
 * @returns {void}
 */
export function set_text_if_changed(el, text) {
	const s = String(text)
	if (el.textContent != s) {
		el.textContent = s
	}
}